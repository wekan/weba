// Ship the unchanged isomorphic filename policy without a Meteor dependency.
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
let source=process.argv[2]||process.env.WEKAN_SOURCE,ancestor=path.resolve(__dirname,'..');
while(!source&&path.dirname(ancestor)!==ancestor){if(fs.existsSync(path.join(ancestor,'imports/lib/fileNameDisplay.js')))source=ancestor;else ancestor=path.dirname(ancestor);}
if(!source)throw Error('Pass the original WeKan checkout as the first argument');
const relative='imports/lib/fileNameDisplay.js',raw=fs.readFileSync(path.join(source,relative)),text=raw.toString('utf8');
const exportMatch=text.match(/\nexport \{([\s\S]*?)\};\s*$/);
if(!exportMatch)throw Error('Original filename exports changed');
const names=exportMatch[1].split(',').map(name=>name.trim()).filter(Boolean);
if(names.some(name=>!/^\w+$/.test(name)))throw Error('Unexpected filename export');
const body=text.slice(0,exportMatch.index),bundle="// Generated by tools/import-wekan-filenames.cjs from unchanged source.\n(function(root){\n'use strict';\nif(root.webaFileNames)return;\n"+body+'\nroot.webaFileNames=Object.freeze({'+names.join(',')+'});\n})(globalThis);\n';
const root=path.resolve(__dirname,'..'),vendor=path.join(root,'vendor/wekan-filenames');fs.mkdirSync(vendor,{recursive:true});
const hash=value=>crypto.createHash('sha256').update(value).digest('hex');
fs.writeFileSync(path.join(vendor,'fileNameDisplay.js'),raw);
fs.writeFileSync(path.join(root,'WeKan/.public/filename-policy.js'),bundle);
fs.writeFileSync(path.join(vendor,'manifest.json'),JSON.stringify({sourceFile:relative,sourceSha256:hash(raw),exports:names,bundleSha256:hash(bundle)},null,2)+'\n');
console.log('Imported unchanged filename policy: '+names.length+' exports');
